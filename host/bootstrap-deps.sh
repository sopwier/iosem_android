#!/usr/bin/env bash
# Install the host build dependencies *without root* on Debian/Ubuntu.
#
# It downloads a small set of .deb files into host/.build/deps, extracts them
# under host/.build/deps/root, and writes host/.build/toolchain.env.  The QEMU
# build script sources that file automatically.  This is a convenience for
# machines where sudo is unavailable; the normal route is:
#
#   sudo apt install build-essential flex bison libglib2.0-dev \
#                    libpixman-1-dev zlib1g-dev libfdt-dev
#
# Only the x86-64 host toolchain is handled.

set -euo pipefail

HOST_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BUILD_DIR="${IOSEM_BUILD_DIR:-$HOST_DIR/.build}"
DEPS_DIR="$BUILD_DIR/deps"
ROOT="$DEPS_DIR/root"
ENV_FILE="$BUILD_DIR/toolchain.env"

if [[ "$(uname -s)" != "Linux" ]]; then
    echo "This helper is Linux-only. Install the build dependencies with your package manager." >&2
    exit 1
fi

if [[ "$(uname -m)" != "x86_64" ]]; then
    echo "This helper currently supports x86_64 Debian/Ubuntu hosts only." >&2
    exit 1
fi

if command -v g++ >/dev/null 2>&1 &&
   command -v flex >/dev/null 2>&1 &&
   command -v bison >/dev/null 2>&1 &&
   printf '#include <libfdt.h>\n' | "${CC:-cc}" -E - >/dev/null 2>&1; then
    echo "Host toolchain already provides g++, flex, bison and libfdt."
    exit 0
fi

command -v apt-get >/dev/null 2>&1 || {
    echo "apt-get is not available; install g++, flex, bison and libfdt-dev manually." >&2
    exit 1
}
command -v dpkg-deb >/dev/null 2>&1 || {
    echo "dpkg-deb is not available; install dpkg-dev or use your package manager." >&2
    exit 1
}
command -v gcc >/dev/null 2>&1 || {
    echo "gcc is not available; install build-essential or a C compiler." >&2
    exit 1
}

GCC_MAJOR="$(gcc -dumpversion 2>/dev/null | cut -d. -f1)"
if [[ ! "$GCC_MAJOR" =~ ^[0-9]+$ ]]; then
    echo "Could not determine the system GCC major version." >&2
    exit 1
fi

mkdir -p "$DEPS_DIR/debs" "$ROOT"

# Package names follow the system GCC major version.  apt-get download resolves
# the archive's current version, so the exact filenames need not be hard-coded.
packages=(
    "g++-$GCC_MAJOR"
    "g++-$GCC_MAJOR-x86-64-linux-gnu"
    "libstdc++-$GCC_MAJOR-dev"
    flex
    bison
    libfdt-dev
)

echo "Downloading host build dependencies into $DEPS_DIR/debs ..."
(
    cd "$DEPS_DIR/debs"
    apt-get download "${packages[@]}"
)

echo "Extracting ..."
for deb in "$DEPS_DIR"/debs/*.deb; do
    dpkg-deb -x "$deb" "$ROOT"
done

# GCC looks for its support files relative to its own prefix.  The extracted
# libstdc++-NN-dev package creates a real .../gcc/.../NN directory that lacks
# cc1plus's internal headers (stddef.h and friends), so replace it with a
# symlink to the system GCC directory.  Then provide the missing linker bits.
gcc_dir="$ROOT/usr/lib/gcc/x86_64-linux-gnu/$GCC_MAJOR"
if [[ -d "$gcc_dir" && ! -L "$gcc_dir" ]]; then
    rm -rf "$gcc_dir"
fi
if [[ ! -e "$gcc_dir" ]]; then
    mkdir -p "$(dirname "$gcc_dir")"
    ln -s "/usr/lib/gcc/x86_64-linux-gnu/$GCC_MAJOR" "$gcc_dir"
fi

mkdir -p "$ROOT/usr/lib/x86_64-linux-gnu" \
         "$ROOT/usr/libexec/gcc/x86_64-linux-gnu/$GCC_MAJOR"
if [[ ! -e "$ROOT/usr/bin/g++" ]]; then
    ln -s "g++-$GCC_MAJOR" "$ROOT/usr/bin/g++"
fi
if [[ ! -e "$ROOT/usr/lib/x86_64-linux-gnu/libstdc++.so" ]]; then
    ln -s /usr/lib/x86_64-linux-gnu/libstdc++.so.6 "$ROOT/usr/lib/x86_64-linux-gnu/libstdc++.so"
fi
if [[ ! -e "$ROOT/usr/libexec/gcc/x86_64-linux-gnu/$GCC_MAJOR/liblto_plugin.so" ]]; then
    ln -s "/usr/libexec/gcc/x86_64-linux-gnu/$GCC_MAJOR/liblto_plugin.so" \
        "$ROOT/usr/libexec/gcc/x86_64-linux-gnu/$GCC_MAJOR/liblto_plugin.so"
fi

cat > "$ENV_FILE" <<EOF
# Generated by host/bootstrap-deps.sh. Source this before building QEMU.
export PATH="$ROOT/usr/bin:\$PATH"
export CPATH="$ROOT/usr/include\${CPATH:+:\$CPATH}"
export CPLUS_INCLUDE_PATH="$ROOT/usr/include/c++/$GCC_MAJOR:$ROOT/usr/include/x86_64-linux-gnu/c++/$GCC_MAJOR\${CPLUS_INCLUDE_PATH:+:\$CPLUS_INCLUDE_PATH}"
export LIBRARY_PATH="$ROOT/usr/lib/x86_64-linux-gnu\${LIBRARY_PATH:+:\$LIBRARY_PATH}"
export CXX=g++-$GCC_MAJOR
export CC=gcc
EOF

# Smoke-test the extracted compiler before declaring success.
tmpdir="$(mktemp -d)"
trap 'rm -rf "$tmpdir"' EXIT
cat > "$tmpdir/test.cc" <<'EOF'
#include <iostream>
int main() { std::cout << "ok\n"; return 0; }
EOF
(
    # shellcheck disable=SC1090
    source "$ENV_FILE"
    "g++-$GCC_MAJOR" "$tmpdir/test.cc" -o "$tmpdir/test"
    "$tmpdir/test" >/dev/null
)

echo "Wrote $ENV_FILE"
echo "Now run: ./host/build-qemu.sh"
